    private boolean insertingFromTo() {
        queryParser();
        queryParsed[2] = dtpFrom.toStringStrict();
        queryParsed[3] = dtpTo.toStringStrict();
        jtfQuery.setText("In [" + queryParsed[0] + "]   where [" + queryParsed[1]
                + "]   from [" + queryParsed[2] + "]   to [" + queryParsed[3] + "]");

        if (queryParsed[2].isEmpty() || queryParsed[3].isEmpty()) {
            jlQueryStatus.setText(" Fill the date 'From' and 'To' and click on query field.");
            return false;
        } else if (dtpFrom.getDateTimeStrict().isAfter(dtpTo.getDateTimeStrict())) {
            jlQueryStatus.setText(" Date 'From' is after date 'To'. Please change it.");
            dtpFrom.clear();
            return false;
        } else {
            jlQueryStatus.setText("");
            return true;
        }
    }

