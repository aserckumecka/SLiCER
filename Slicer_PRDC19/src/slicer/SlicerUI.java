    private class ExecuteQuery implements Runnable {

        @Override
        public void run() {
            while (slicer.eventBuffer.size() > 0) {
                try {
                    Thread.sleep(1000);
                } catch (InterruptedException ex) {
                    Logger.getLogger(SlicerUI.class.getName()).log(Level.SEVERE, null, ex);
                }
            }

            if (insertingFromTo()) {
                int blocksInCloud = 0;
                int blocksInCache = 0;
                float downloadSize = 0;
                selectedTerm = new ArrayList<>();
                selectedValue = new ArrayList<>();
                queryResult = new ArrayList<>();
                matchDataBlocks = new ArrayList();
                matchIndexBlocks = new ArrayList();

                jlBlockCached.setText("0");
                jlBlockClouds.setText("0");
                jlEvtFound.setText("0");
                jlDownloadSize.setText("0");
                jlDownloadCost.setText("0");

                try {
                    // (it doesn't exist yet!) stop the thread that controls the cache size
                    // (to avoid deleting a cached index mentioned in this query).

                    //*******************************************************************************************************
                    //Listing the devices choosen by user...
                    String[] devices = queryParsed[0].split(",");
                    //Getting the data and time parameters filled by user...
                    LocalDateTime ldtFrom = LocalDateTime.parse(queryParsed[2], formatter);
                    LocalDateTime ldtTo = LocalDateTime.parse(queryParsed[3], formatter);
                    //Getting the terms and creating the query...
                    String[] keyValueFields = queryParsed[1].split(",");
                    for (int i = 0; i < keyValueFields.length; i++) {
                        String[] kv = keyValueFields[i].split("=");

                        selectedTerm.add(kv[0].trim());

                        selectedValue.add(kv[1].trim());
                    }

                    //Cleaning the tmp folder...
                    jlQueryStatus.setText(" Cleaning tmp folder...");
                    File data = new File(slicer.tmp_path + "/data");
                    File index = new File(slicer.tmp_path + "/index");
                    File events = new File(slicer.tmp_path + "/events");

                    if (!data.exists()) {
                        Files.createDirectory(data.toPath());
                    }
                    if (!index.exists()) {
                        Files.createDirectory(index.toPath());
                    }
                    if (!events.exists()) {
                        Files.createDirectory(events.toPath());
                    }

                    File[] dataFiles = data.listFiles();
                    for (int i = 0; i < dataFiles.length; i++) {
                        List<File> tmpFiles = Files.walk(dataFiles[i].toPath())
                                .filter(Files::isRegularFile)
                                .map(Path::toFile)
                                .collect(Collectors.toList());
                        for (int j = 0; j < tmpFiles.size(); j++) {
                            tmpFiles.get(j).delete();
                        }
                        dataFiles[i].delete();
                    }

                    File[] indexFiles = index.listFiles();
                    for (int i = 0; i < indexFiles.length; i++) {
                        List<File> tmpFiles = Files.walk(indexFiles[i].toPath())
                                .filter(Files::isRegularFile)
                                .map(Path::toFile)
                                .collect(Collectors.toList());
                        for (int j = 0; j < tmpFiles.size(); j++) {
                            tmpFiles.get(j).delete();
                        }
                        indexFiles[i].delete();
                    }

                    File[] eventFiles = events.listFiles();
                    for (int i = 0; i < eventFiles.length; i++) {
                        List<File> tmpFiles = Files.walk(eventFiles[i].toPath())
                                .filter(Files::isRegularFile)
                                .map(Path::toFile)
                                .collect(Collectors.toList());
                        for (int j = 0; j < tmpFiles.size(); j++) {
                            tmpFiles.get(j).delete();
                        }
                        eventFiles[i].delete();
                    }

                    //*******************************************************************************************************
                    //Selecting the matching blocks...
                    jlQueryStatus.setText(" Selecting the index blocks...");
                    for (int i = 0; i < devices.length; i++) {
                        devices[i] = devices[i].trim();
                        List<File> cachedIndexes = Files.walk(Paths.get(slicer.cache_path + "/" + devices[i] + "/index"))
                                .filter(Files::isRegularFile)
                                .map(Path::toFile)
                                .collect(Collectors.toList());
                        for (int j = 0; j < cachedIndexes.size(); j++) {
                            if (cachedIndexes.get(j).isHidden()) {
                                continue;
                            }
                            String fullBlockPath = cachedIndexes.get(j).toString();
                            String blockName = cachedIndexes.get(j).getName();
                            int from = blockName.indexOf("_") + 1;
                            int to = blockName.indexOf("__");
                            String blockDates = blockName.substring(from, to);
                            String dtF = blockDates.substring(0, blockDates.indexOf("_"));
                            String dtT = blockDates.substring(blockDates.indexOf("_") + 1);
                            LocalDateTime ldtBlockF = LocalDateTime.parse(dtF, formatter);
                            LocalDateTime ldtBlockT = LocalDateTime.parse(dtT, formatter);

                            if ((ldtBlockF.isAfter(ldtFrom) && ldtBlockT.isBefore(ldtTo))
                                    || (ldtBlockF.isBefore(ldtFrom) && ldtBlockT.isAfter(ldtFrom))
                                    || (ldtBlockT.isAfter(ldtTo) && ldtBlockF.isBefore(ldtTo))) {
                                if (blockName.endsWith("**")) {
                                    fullBlockPath = fullBlockPath.replace("**", ""); //if this block is in the cloud...
                                    blockName = fullBlockPath.replace(slicer.cache_path, slicer.cloud_path);
                                    Files.copy(
                                            Paths.get(blockName), //source
                                            Paths.get(fullBlockPath),//destination
                                            StandardCopyOption.COPY_ATTRIBUTES);
                                    Files.delete(cachedIndexes.get(j).toPath());
                                    downloadSize = downloadSize + new File(fullBlockPath).length();
                                }
                                matchIndexBlocks.add(new File(fullBlockPath));

                                //Storing the corresponding data block...
                                String temp = fullBlockPath.replace("/index", "/data");
                                temp = temp.replace("__" + slicer.indexer, "");
                                matchDataBlocks.add(new File(temp));
                                System.out.println("New Matching block added: " + temp);
                            }
                        }
                    }

                    //******************************************************************************************************
                    //Uncompressing index blocks...
                    jlQueryStatus.setText(" Extracting the index blocks...");
                    jpb.setMinimum(0);
                    jpb.setMaximum(matchIndexBlocks.size());
                    String temp = null;

                    for (int i = 0; i < matchIndexBlocks.size(); i++) {
                        jpb.setValue(i + 1);
                        String blockExt = matchIndexBlocks.get(i).getName();
                        if (blockExt.endsWith("xz")) {
                            String blockName = matchIndexBlocks.get(i).getName();
                            blockName = blockName.substring(0, blockName.indexOf(slicer.compress) - 1);
                            File blockDest = new File(slicer.tmp_path + "/index/" + blockName);
                            Xz.decoder(matchIndexBlocks.get(i), blockDest);
                        } else if (blockExt.endsWith("7z")) {
                            //SevenZip.sevenZipUncompressCommandLine(src, dst);
                        } else if (blockExt.endsWith("zip")) {
                            //Zip.uncompressDirectory(src, dst); //not implemented yet.
                        } else if (blockExt.endsWith("zpaq")) {
                            //Zpaq.zpaqUncompress(src, dst); //it doesn't work yet.
                        }
                        // Change the path to the new location, the tmp folder.
                        temp = matchIndexBlocks.get(i).toString().replace(
                                matchIndexBlocks.get(i).getParent(),
                                slicer.tmp_path + "/index");
                        temp = temp.replace("." + slicer.compress, "");
                        matchIndexBlocks.set(i, new File(temp));
                    }

                    jlQueryStatus.setText(" Running the query...");
                    List<Integer> blocksToRemove = new ArrayList<>();

                    //*******************************************************************************************************
                    //If Lucene...
                    if (slicer.indexer.equals("lr") || slicer.indexer.equals("lf")) {
                        BooleanQuery.Builder builder = new BooleanQuery.Builder();
                        BooleanQuery booleanQuery;

                        for (int i = 0; i < selectedValue.size(); i++) {
                            Query query = new TermQuery(new Term("contents", selectedValue.get(i)));
                            builder.add(query, BooleanClause.Occur.MUST);
                        }

                        booleanQuery = builder.build();
                        List<String> qr = new ArrayList<>();

                        for (int i = 0; i < matchIndexBlocks.size(); i++) {
                            jpb.setValue(i + 1);
                            // qr.get(i) contains an uncompressed data block name + "/eventId" 
                            //( i.e. COLECT_2017-11-17T14:58:36.372_2017-11-17T15:33:36.161/10581 )
                            qr = Lucene.search(booleanQuery, matchIndexBlocks.get(i));
                            if (qr != null) {
                                for (int j = 0; j < qr.size(); j++) {
                                    // Add a list of events matching the query from each block.
                                    // Every path contains the eventId, which is the name of event.
                                    queryResult.add(qr.get(j));
                                }
                            } else {
                                blocksToRemove.add(i); // This block isn't needed.
                            }
                        }
                        //Filling the number of events for the query...
                        jlEvtFound.setText(String.valueOf(queryResult.size()));
                    } //*******************************************************************************************************
                    else { // Bloom filter...

                        // This code verifies which index file contains or not the term(s)
                        // searched. (Using bloom filter is impossible to know now how many
                        // events exists in every block, even if they exists certanty).
                        // Set as null the blocks not matching the query.
                        //LongFastBloomFilter lfb;
                        
                        BF bloom = new BF();
                        for (int i = 0; i < matchIndexBlocks.size(); i++) {
                            jpb.setValue(i + 1);
                            int countSelectedItems = 0;
                            boolean containTerm = false;
                            File[] arrayFile = matchIndexBlocks.get(i).listFiles();
                            for (int j = 0; j < arrayFile.length; j++) {
                                for (int z = 0; z < selectedTerm.size(); z++) {
                                    String fileName = arrayFile[j].getName();
                                    String selTerm = selectedTerm.get(z) + ".bf";
                                    //System.out.println("filename: " + fileName + "  |  selected term: " + selTerm);
                                    if (fileName.equals(selTerm)) {
                                        File file = arrayFile[j];
                                        //lfb = BF.retrieveBloom(file);
                                        //System.out.println("File to search: " + arrayFile[j]);
                                        //System.out.println("Value to search: " + selectedValue.get(z));
                                        String value = selectedValue.get(z);
                                        //if (lfb.contains(value.getBytes())) { // It isn't in the block...
                                        if (bloom.verifyTerm(file, value)) { // It isn't in the block...
                                            containTerm = true;
                                            countSelectedItems++;
                                            //System.out.println("Value found");
                                        } else {
                                            j = arrayFile.length; // break the loop and continue.
                                            containTerm = false;
                                            //System.out.println("Value Not found");
                                        }
                                        break;
                                    }
                                }
                            }
                            if (!containTerm || countSelectedItems != selectedTerm.size()) {
                                blocksToRemove.add(i); // This block isn't needed.
                            }
                        }
                        //Filling the number of events for the query...
                        jlEvtFound.setText("-");
                    }
                    //*******************************************************************************************************

                    // Deleting the block paths that doesn't match the query.
                    for (int i = blocksToRemove.size() - 1; i >= 0; i--) {
                        int ind = blocksToRemove.get(i);
                        matchDataBlocks.remove(ind);
                    }

                    //System.out.println("matchDataBlocks size:  " + matchDataBlocks.size());

                    for (int i = 0; i < matchDataBlocks.size(); i++) {
                        // It means that the block isn't in cache, it's only in the cloud.
                        if (!matchDataBlocks.get(i).toString().equals(slicer.tmp_path)) {
                            if (!matchDataBlocks.get(i).exists()) {
                                blocksInCloud++;
                                String newPath = matchDataBlocks.get(i).toString().replace(slicer.cache_path, slicer.cloud_path);
                                matchDataBlocks.set(i, new File(newPath));
                                downloadSize = downloadSize + matchDataBlocks.get(i).length();
                                System.out.println("It not exists in cache: " + matchDataBlocks.get(i));
                            } else {
                                blocksInCache++;
                            }
                        }
                    }
                    jlBlockCached.setText(String.valueOf(blocksInCache));
                    jlBlockClouds.setText(String.valueOf(blocksInCloud));

                    float gbSize = downloadSize / 1024 / 1024 / 1024;
                    float mbSize = downloadSize / 1024 / 1024;
                    float kbSize = downloadSize / 1024;

                    if (gbSize > 1) {
                        jlDownloadSize.setText(String.format("%.2f", gbSize) + " GB");
                        jlDownloadCost.setText(String.format("$ %.5f", gbSize * Float.parseFloat(slicer.cost)));
                    } else if (mbSize > 1) {
                        jlDownloadSize.setText(String.format("%.2f", mbSize) + " MB");
                        jlDownloadCost.setText(String.format("$ %.5f", gbSize * Float.parseFloat(slicer.cost)));
                    } else if (kbSize > 1) {
                        jlDownloadSize.setText(String.format("%.2f", kbSize) + " KB");
                        jlDownloadCost.setText(String.format("$ %.5f", gbSize * Float.parseFloat(slicer.cost)));
                    }

                    jtaQueryResult.setText("");
                } catch (IOException ex) {
                    Logger.getLogger(SlicerUI.class.getName()).log(Level.SEVERE, null, ex);
                }
                if (blocksInCache + blocksInCloud > 0) {
                    jbDownloadEvents.setEnabled(true);
                }
                jpb.setValue(0);
                jlQueryStatus.setText(" Query finished!");
            }
        }
    }

