    private void queryParser() {
        String query = jtfQuery.getText();

        for (int i = 0; i < queryParsed.length; i++) {
            int begin = query.indexOf("[") + 1;
            int end = query.indexOf("]");
            queryParsed[i] = query.substring(begin, end);
            query = query.substring(end + 1, query.length());
        }
    }

