    private class DownloadEvents implements Runnable {

        @Override
        public void run() {
            jpb.setMinimum(0);
            jpb.setMaximum(matchDataBlocks.size());

            // Coping the blocks from cloud to cache (for those who are not in the cache).
            for (int j = 0; j < matchDataBlocks.size(); j++) {
                jlQueryStatus.setText(" Transferring the blocks from Cache/Cloud...");
                jpb.setValue(j + 1);

                String dataBlockFile = matchDataBlocks.get(j).toString();
                //If this block is not in the cache, transfer it from cloud to cache.
                if (dataBlockFile.contains(slicer.cloud_path)) {
                    String blockToCache = dataBlockFile.replace(slicer.cloud_path, slicer.cache_path);
                    try {
                        Files.copy(
                                Paths.get(dataBlockFile),
                                Paths.get(blockToCache),
                                StandardCopyOption.COPY_ATTRIBUTES);
                    } catch (IOException ex) {
                        Logger.getLogger(SlicerUI.class.getName()).log(Level.SEVERE, null, ex);
                    }
                    matchDataBlocks.set(j, new File(blockToCache));
                }

                //Setting the destination file (tmp folder) and uncompressing them to.
                String dataBlockName = matchDataBlocks.get(j).getName();
                dataBlockName = dataBlockName.substring(0, dataBlockName.indexOf(slicer.compress) - 1);

                // Uncompressing the data blocks...
                if (dataBlockFile.endsWith("xz")) {
                    File blockDest = new File(slicer.tmp_path + "/data/" + dataBlockName);
                    Xz.decoder(matchDataBlocks.get(j), blockDest);

                    String temp = slicer.tmp_path + "/data/" + matchDataBlocks.get(j).getName();
                    temp = temp.substring(0, temp.indexOf(slicer.compress) - 1);
                    matchDataBlocks.set(j, new File(temp));
                } else if (dataBlockFile.endsWith("7z")) {
                    //SevenZip.sevenZipUncompressCommandLine(src, dst);
                } else if (dataBlockFile.endsWith("zip")) {
                    //Zip.uncompressDirectory(src, dst); //not implemented yet.
                }
            }

            String buffer = new String();
            int bufferCount = 0;
            jlQueryStatus.setText(" Looking for the events matching the query...");

            //*******************************************************************************************************
            // If Bloom filter...
            // Read all events inside each matchDataBlocks and search for fields (selectedTerm) and values (selectedValue).
            // If the event match with k=v, add the path of this event to queryResult.
            boolean containTerm = false;
            int evtCount = 0;
            if (slicer.indexer.equals("bf")) {
                List<Path> evtFrom = new ArrayList<>();
                List<Path> evtTo = new ArrayList<>();

                try {
                    jlEvtFound.setText("-");
                    // for each event block folder...
                    for (int i = 0; i < matchDataBlocks.size(); i++) {
                        jpb.setValue(i + 1);
                        File[] dataFiles = matchDataBlocks.get(i).listFiles();
                        // read each event to verify if...
                        for (int j = 0; j < dataFiles.length; j++) {
                            BufferedReader br = new BufferedReader(new FileReader(dataFiles[j]));
                            String event = br.readLine();
                            // each key/value pair is in this event.
                            for (int x = 0; x < selectedTerm.size(); x++) {
                                // It only works for CEF format...
                                if (!event.contains(selectedTerm.get(x) + "=" + selectedValue.get(x))) {
                                    containTerm = false;
                                    break;
                                } else {
                                    containTerm = true;
                                }
                            }
                            if (containTerm) {
                                evtCount++;
                                bufferCount++;
                                buffer = buffer + evtCount + " - " + event + "\n\n";
                                if (bufferCount >= slicer.buffer) {
                                    jtaQueryResult.append(buffer);
                                    bufferCount = 0;
                                    buffer = "";
                                }

                                //adding to the Data Query screen...
                                //jtaQueryResult.append(evtCount + " - " + event + "\n\n");
                                //coping event to tmp's event folder...
                                String eventId = dataFiles[j].getName();
                                File tempFile = new File(dataFiles[j].getParent());
                                Path evtDst = Paths.get(slicer.tmp_path + "/events/" + tempFile.getName() + "#" + eventId);
                                Path evtSrc = dataFiles[j].toPath();
                                evtFrom.add(evtSrc);
                                evtTo.add(evtDst);

                            }
                            containTerm = false;
                        }
                    }
                    if (bufferCount > 0) {
                        jtaQueryResult.append(buffer);
                    }

                    jlEvtFound.setText(String.valueOf(evtCount));
                    jlQueryStatus.setText(" Download and extraction finished!");

                    //Coping the events matching the query to tmp|events folder.
                    if (evtCount > 0) {
                        for (int i = 0; i < evtFrom.size(); i++) {
                            Files.copy(evtFrom.get(i), evtTo.get(i), StandardCopyOption.COPY_ATTRIBUTES);
                        }
                    }
                } catch (IOException ex) {
                    Logger.getLogger(SlicerUI.class.getName()).log(Level.SEVERE, null, ex);
                }
            } //*******************************************************************************************************
            else {
                // If Lucene...
                // Get the events matching the query, put them into tmp folder, and show them on the Data Query screen.
                List<File> querySrc = new ArrayList<>();
                List<File> queryDst = new ArrayList<>();

                BufferedReader br = null;
                try {
                    jpb.setMaximum(queryResult.size());
                    for (int j = 0; j < queryResult.size(); j++) {
                        jpb.setValue(j + 1);
                        querySrc.add(new File(slicer.tmp_path + "/data/" + queryResult.get(j)));
                        String temp = queryResult.get(j).replace("/", "#");
                        queryDst.add(new File(slicer.tmp_path + "/events/" + temp));

                        br = new BufferedReader(new FileReader(querySrc.get(j)));
                        bufferCount++;
                        buffer = buffer + (j + 1) + " - " + br.readLine() + "\n\n";
                        if (bufferCount >= slicer.buffer) {
                            jtaQueryResult.append(buffer);
                            bufferCount = 0;
                            buffer = "";
                        }
                    }
                    if (bufferCount > 0) {
                        jtaQueryResult.append(buffer);
                    }

                    jlQueryStatus.setText(" Download and extraction finished!");

                    for (int j = 0; j < queryResult.size(); j++) {
                        Files.copy(
                                querySrc.get(j).toPath(),
                                queryDst.get(j).toPath(),
                                StandardCopyOption.COPY_ATTRIBUTES);
                    }
                } catch (IOException ex) {
                    Logger.getLogger(SlicerUI.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
            //*******************************************************************************************************

            jbExecuteQuery.setEnabled(true);
            jbExport.setEnabled(true);
            JOptionPane.showMessageDialog(null,
                    "Events are temporarily available at: \n" + slicer.tmp_path + "/events/\n"
                    + "You can save those events you want from there\nor all events shown by clicking on 'Export'",
                    "Events copied",
                    JOptionPane.INFORMATION_MESSAGE);
            jpb.setValue(0);
        }
    }

